/** הנוסח של תקנון או מדיניות: מהמסד אם המנהל שמר נוסח, אחרת הנוסח הראשוני */
export const getSiteContent = cache(async (key: ContentKey): Promise<SiteContent & { custom: boolean }> => {
  const supabase = await createClient();
  const { data, error } = await supabase.from("site_content").select("*").eq("key", key).maybeSingle();
  if (error || !data) return { ...DEFAULT_CONTENT[key], updated_at: null, custom: false };
  return { ...(data as SiteContent), custom: true };
});
